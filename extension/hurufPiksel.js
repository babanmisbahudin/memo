export const TINGGI_HURUF = 7;
// Tinggi satu baris teks, termasuk ekor huruf dan jarak antarbaris.
export const TINGGI_BARIS = 10;

export const HURUF = Object.fromEntries(Object.entries(DATA).map(([c, s]) => [c, s.split(' ')]));

const huruf = c => HURUF[c] ?? HURUF['?'];

// Lebar teks dalam piksel layar bila satu piksel huruf = `u` piksel layar.
export function lebarTeks(teks, u) {
    let n = 0;
    for (const c of teks)
        n += huruf(c)[0].length + 1;
    return Math.max(0, n - 1) * u;
}

// Gambar `teks` dengan pojok kiri atas di (x, y). `jumlah` membatasi berapa
// huruf yang sudah tampak (efek mesin ketik); `geser(i)` memberi geser
// vertikal (dalam satuan u) untuk huruf ke-i, dipakai efek ombak/loncat.
export function tulisTeks(cr, teks, x, y, u, [r, g, b, a = 1], { jumlah = Infinity, geser = null } = {}) {
    cr.setSourceRGBA(r / 255, g / 255, b / 255, a);
    let cx = x;
    let i = 0;
    for (const c of teks) {
        if (i >= jumlah)
            break;
        const baris = huruf(c);
        const dy = (geser?.(i) ?? 0) * u;
        baris.forEach((isi, j) => {
            // Kotak berderet digabung jadi satu persegi panjang.
            let mulai = -1;
            for (let k = 0; k <= isi.length; k++) {
                if (isi[k] === '#') {
                    if (mulai < 0)
                        mulai = k;
                } else if (mulai >= 0) {
                    cr.rectangle(cx + mulai * u, y + dy + j * u, (k - mulai) * u, u);
                    mulai = -1;
                }
            }
        });
        cx += (baris[0].length + 1) * u;
        i++;
    }
    cr.fill();
}
